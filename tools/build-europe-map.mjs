// Generates js/europe-map.js (static SVG path data for the Journey page).
// Usage (from a scratch dir with the packages below installed): node build-europe-map.mjs > <repo>/js/europe-map.js
// Needs: npm i world-atlas@2 topojson-client d3-geo
import { createRequire } from "node:module";
import { geoAzimuthalEqualArea, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/countries-50m.json");
const countries = feature(topo, topo.objects.countries).features;

// Azimuthal equal-area centred on Central Europe (like the EU's ETRS89-LAEA).
const W = 1000, H = 700;
const projection = geoAzimuthalEqualArea()
  .rotate([-13, -52])
  .scale(1900)
  .translate([W / 2, H / 2])
  .clipExtent([[-260, -220], [1300, 960]])
  .precision(0.3);
const path = geoPath(projection).digits(1);

const CZ_NAME = "Czechia";
let land = "";
let cz = "";
for (const f of countries) {
  const d = path(f);
  if (!d) continue;
  if (f.properties.name === CZ_NAME) cz = d; else land += d;
}
if (!cz) throw new Error("Czechia not found");

const czFeature = countries.find(f => f.properties.name === CZ_NAME);
const [[cx0, cy0], [cx1, cy1]] = path.bounds(czFeature);

const cityLonLat = {
  valmez:   [17.9716, 49.4719], // Valašské Meziříčí
  ostrava:  [18.2625, 49.8209],
  lyon:     [4.8357, 45.7640]
};
const cities = {};
for (const [k, ll] of Object.entries(cityLonLat)) {
  const [x, y] = projection(ll);
  cities[k] = [Math.round(x * 100) / 100, Math.round(y * 100) / 100];
}

const r2 = n => Math.round(n * 100) / 100;
const lx = cities.lyon[0];
const frames = {
  // x/y = centre, w = visible width in map units (height follows container aspect)
  europe: { x: 492, y: 322, w: 1400 },
  cz:     { x: r2((cx0 + cx1) / 2), y: r2((cy0 + cy1) / 2), w: r2((cx1 - cx0) * 1.55) },
  route:  { x: r2((lx + cx1) / 2), y: r2((cities.lyon[1] + cy0) / 2 + 6), w: r2((cx1 - lx) * 1.32) }
};

const out = {
  size: [W, H],
  cities,
  frames,
  cz,
  land
};

process.stdout.write(
`/* Generated by tools/build-europe-map.mjs from Natural Earth 50m (via world-atlas). Do not edit by hand. */
window.EUROPE_MAP = ${JSON.stringify(out)};
`);
